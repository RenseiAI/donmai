// Command gen records the digests of the canonical schema and fixture suite in
// compiled Go source. The parity test recomputes them, so artifact edits cannot
// drift silently from the contract revision reviewed by Go consumers.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
)

const contractVersion = "donmai.execution-cell/v1alpha1"

type versionedArtifact struct {
	ContractVersion string `json:"contractVersion"`
}

func readArtifact(name string) ([]byte, string, error) {
	var (
		raw []byte
		err error
	)
	switch name {
	case "contract.schema.json":
		raw, err = os.ReadFile("contract.schema.json")
	case "fixtures.json":
		raw, err = os.ReadFile("fixtures.json")
	default:
		return nil, "", fmt.Errorf("unsupported artifact %q", name)
	}
	if err != nil {
		return nil, "", fmt.Errorf("read %s: %w", name, err)
	}
	var header versionedArtifact
	if err := json.Unmarshal(raw, &header); err != nil {
		return nil, "", fmt.Errorf("decode %s: %w", name, err)
	}
	if header.ContractVersion != contractVersion {
		return nil, "", fmt.Errorf("%s contractVersion %q, want %q", name, header.ContractVersion, contractVersion)
	}
	digest := sha256.Sum256(raw)
	return raw, hex.EncodeToString(digest[:]), nil
}

func main() {
	_, schemaDigest, err := readArtifact("contract.schema.json")
	if err != nil {
		panic(err)
	}
	_, fixtureDigest, err := readArtifact("fixtures.json")
	if err != nil {
		panic(err)
	}
	source := []byte(fmt.Sprintf(`// Code generated by executioncell/gen; DO NOT EDIT.
// Run "go generate ./executioncell" to regenerate.

package executioncell

const (
	ContractSchemaSHA256 = %q
	FixtureSuiteSHA256 = %q
)
`, schemaDigest, fixtureDigest))
	formatted, err := format.Source(source)
	if err != nil {
		panic(fmt.Errorf("format generated source: %w", err))
	}
	if err := os.WriteFile("artifacts_gen.go", formatted, 0o600); err != nil {
		panic(fmt.Errorf("write artifacts_gen.go: %w", err))
	}
}
