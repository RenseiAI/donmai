// This file renders the generated harness support page (matrix/SUPPORT.md):
// one row per harness and session mode, with the OSS columns, all derived
// from the live harness manifests, the hand-authored cells (stability/smoked
// evidence), and the hand-authored binary pins. It publishes what the code
// already declares; it never invents enforcement or eligibility.
//
// Column derivations (each traces to exactly one declaration):
//   - launch lane: the session mode itself (autonomous=headless,
//     human_controlled=interactive).
//   - model delivery: the mode's prompt profile UserDelivery values.
//   - effort: the harness Caps.SupportsReasoningEffort flag.
//   - tool delivery: the mode's tool/lifecycle NativeToolPolicyDelivery +
//     PermissionConfigDelivery values.
//   - mcp delivery: the mode's tool/lifecycle MCPDelivery values.
//   - extension delivery: the mode's tool/lifecycle ToolPluginDelivery values.
//   - exec tool/network deny: the generated per-mode deny-baseline records
//     (workspace-write grant at index 0 via RenderExecutionSecurity).
//   - resume: the harness Caps.SupportsSessionResume flag.
//   - events: the mode's lifecycle delivery, fidelity, and event count.
//   - attach: the harness Caps.SupportsInteractivePTY flag.
//   - evidence tier / production eligible: the mode's tool/lifecycle profile
//     fields.
//   - binary pin: the hand-authored harnessBinaryPins PinnedVersion ("-" when
//     the harness ships no external binary).
//   - stability / smoked: aggregates over the hand-authored validCells for
//     the harness ("-" stability when the harness anchors no cell).
//
// A mode that declares several tool/lifecycle profiles (codex interactive
// today) joins the per-profile values with " / " after sorting unique.

// RenderSupportPage renders the deterministic SUPPORT.md content for built.
// Rows sort by harness name, then mode. Output ends with exactly one trailing
// newline and contains no timestamps, so the parity test can byte-compare it.
func RenderSupportPage(built *Built) string {
	var buf strings.Builder
	buf.WriteString("<!-- Code generated by matrix/gen; DO NOT EDIT.\n")
	buf.WriteString("     Run `make generate` (go generate ./matrix/...) to regenerate. -->\n\n")
	buf.WriteString("# Harness support\n\n")
	buf.WriteString("One row per harness and session mode, generated from the harness\n")
	buf.WriteString("manifests, the hand-authored cells (stability/smoked), and the\n")
	buf.WriteString("hand-authored binary pins. A hand edit here fails the parity gate;\n")
	buf.WriteString("a code change without regeneration fails it too.\n\n")
	buf.WriteString("| harness | mode | launch lanes | model delivery | effort | tool delivery | mcp delivery | extension delivery | exec tool deny | exec network deny | resume | events | attach | evidence tier | prod eligible | binary pin | stability | smoked |\n")
	buf.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")

	byName := map[agent.HarnessName]HarnessRow{}
	for _, h := range built.Harnesses {
		byName[h.Name] = h
	}
	pins := map[agent.HarnessName]HarnessBinaryPin{}
	for _, p := range built.Matrix.BinaryPins {
		pins[p.Harness] = p.HarnessBinaryPin
	}

	type rowKey struct {
		harness agent.HarnessName
		mode    agent.PromptSessionMode
	}
	var keys []rowKey
	for _, h := range built.Harnesses {
		for _, mode := range supportModes(h) {
			keys = append(keys, rowKey{harness: h.Name, mode: mode})
		}
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].harness != keys[j].harness {
			return keys[i].harness < keys[j].harness
		}
		return keys[i].mode < keys[j].mode
	})

	for _, k := range keys {
		h := byName[k.harness]
		buf.WriteString("| " + strings.Join([]string{
			escapeCell(string(h.Name)),
			escapeCell(string(k.mode)),
			escapeCell(launchLanes(k.mode)),
			escapeCell(joinSorted(promptUserDeliveries(h, k.mode))),
			escapeCell(boolCell(h.Caps.SupportsReasoningEffort)),
			escapeCell(joinSorted(toolDeliveries(h, k.mode))),
			escapeCell(joinSorted(mcpDeliveries(h, k.mode))),
			escapeCell(joinSorted(extensionDeliveries(h, k.mode))),
			escapeCell(execToolDeny(h, k.mode)),
			escapeCell(execNetworkDeny(h, k.mode)),
			escapeCell(boolCell(h.Caps.SupportsSessionResume)),
			escapeCell(joinSorted(eventCells(h, k.mode))),
			escapeCell(boolCell(h.Caps.SupportsInteractivePTY)),
			escapeCell(joinSorted(evidenceTiers(h, k.mode))),
			escapeCell(prodEligibleCell(h, k.mode)),
			escapeCell(binaryPinCell(pins, h.Name)),
			escapeCell(stabilityCell(built, h.Name)),
			escapeCell(smokedCell(built, h.Name)),
		}, " | ") + " |\n")
	}
	buf.WriteString(renderSupportV2Section(built))
	return buf.String()
}

// supportModes is the mode set for one harness row: the union of the prompt
// and tool/lifecycle profile modes, matching harnessExecutionSecurityRows.
func supportModes(h HarnessRow) []agent.PromptSessionMode {
	seen := map[agent.PromptSessionMode]bool{}
	var modes []agent.PromptSessionMode
	for _, profile := range h.PromptDelivery {
		if !seen[profile.Mode] {
			seen[profile.Mode] = true
			modes = append(modes, profile.Mode)
		}
	}
	for _, profile := range h.ToolLifecycle {
		if !seen[profile.Mode] {
			seen[profile.Mode] = true
			modes = append(modes, profile.Mode)
		}
	}
	sort.Slice(modes, func(i, j int) bool { return modes[i] < modes[j] })
	return modes
}

// toolProfiles returns the tool/lifecycle profiles for one harness and mode,
// sorted by profile ID for deterministic joins.
func toolProfiles(h HarnessRow, mode agent.PromptSessionMode) []agent.ToolLifecycleProfile {
	var out []agent.ToolLifecycleProfile
	for _, profile := range h.ToolLifecycle {
		if profile.Mode == mode {
			out = append(out, profile)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func launchLanes(mode agent.PromptSessionMode) string {
	if mode == agent.PromptModeHumanControlled {
		return "interactive"
	}
	return "headless"
}

func promptUserDeliveries(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range h.PromptDelivery {
		if profile.Mode == mode && string(profile.UserDelivery) != "" {
			out = append(out, string(profile.UserDelivery))
		}
	}
	return out
}

func toolDeliveries(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range toolProfiles(h, mode) {
		for _, kind := range []agent.ToolDeliveryKind{profile.NativeToolPolicyDelivery, profile.PermissionConfigDelivery} {
			if string(kind) != "" {
				out = append(out, string(kind))
			}
		}
	}
	return out
}

func mcpDeliveries(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range toolProfiles(h, mode) {
		if string(profile.MCPDelivery) != "" {
			out = append(out, string(profile.MCPDelivery))
		}
	}
	return out
}

func extensionDeliveries(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range toolProfiles(h, mode) {
		if string(profile.ToolPluginDelivery) != "" {
			out = append(out, string(profile.ToolPluginDelivery))
		}
	}
	return out
}

func execToolDeny(h HarnessRow, mode agent.PromptSessionMode) string {
	for _, row := range h.ExecutionSecurity {
		if row.Mode == mode {
			return string(row.ToolDenyBaseline)
		}
	}
	return "-"
}

func execNetworkDeny(h HarnessRow, mode agent.PromptSessionMode) string {
	for _, row := range h.ExecutionSecurity {
		if row.Mode == mode {
			return string(row.NetworkDenyBaseline)
		}
	}
	return "-"
}

func eventCells(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range toolProfiles(h, mode) {
		out = append(out, fmt.Sprintf("%s(%s,%d)", string(profile.LifecycleDelivery), string(profile.LifecycleFidelity), len(profile.LifecycleEvents)))
	}
	return out
}

func evidenceTiers(h HarnessRow, mode agent.PromptSessionMode) []string {
	var out []string
	for _, profile := range toolProfiles(h, mode) {
		if profile.EvidenceTier != "" {
			out = append(out, profile.EvidenceTier)
		}
	}
	return out
}

func prodEligibleCell(h HarnessRow, mode agent.PromptSessionMode) string {
	profiles := toolProfiles(h, mode)
	if len(profiles) == 0 {
		return "-"
	}
	var out []string
	for _, profile := range profiles {
		out = append(out, boolCell(profile.ProductionEligible))
	}
	return joinSorted(out)
}

func binaryPinCell(pins map[agent.HarnessName]HarnessBinaryPin, name agent.HarnessName) string {
	pin, ok := pins[name]
	if !ok || pin.PinnedVersion == "" {
		return "-"
	}
	return pin.PinnedVersion
}

// stabilityCell aggregates the hand-authored cell stabilities for one
// harness: the sorted unique stability values joined with "/". A harness
// with no cell (the bare interactive shell today) reports "-".
func stabilityCell(built *Built, name agent.HarnessName) string {
	seen := map[string]bool{}
	var out []string
	for _, c := range built.Matrix.Cells {
		if c.Harness != name || c.Stability == "" || seen[c.Stability] {
			continue
		}
		seen[c.Stability] = true
		out = append(out, c.Stability)
	}
	if len(out) == 0 {
		return "-"
	}
	sort.Strings(out)
	return strings.Join(out, "/")
}

// smokedCell reports whether any hand-authored cell for the harness proved
// it in a smoke lane.
func smokedCell(built *Built, name agent.HarnessName) string {
	for _, c := range built.Matrix.Cells {
		if c.Harness == name && c.Smoked {
			return "yes"
		}
	}
	return "no"
}

func boolCell(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func joinSorted(values []string) string {
	seen := map[string]bool{}
	var out []string
	for _, v := range values {
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	if len(out) == 0 {
		return "-"
	}
	sort.Strings(out)
	return strings.Join(out, " / ")
}

func escapeCell(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}

// ---------------------------------------------------------------------------
// Harness support v2: versioned per-harness contract (harness-support/v2).
// One evidence-backed fact per axis per harness; missing proof stays
// unverified. Supported/unsupported carry public evidence refs; unverified
// carries none. SUPPORT.md v2 and harnesses.json render the same in-memory
// rows (HarnessRow.SupportV2), never re-derived claims.
// Evidence (all in Built, all public): profile:<tool-lifecycle id> for
// headless/interactive, gated on the profile's own evidence tier
// (ProductionEligible or a verified tier); cell:<harness>/<endpoint>/<host>
// plus smoke:<lane> for local-auth and credential delivery, gated on the
// cell's derived Smoked flag and proving lanes; capability:<id>@<adapter>#<mode>
// for code, A2A, architecture, token/cost, and dispatch-spawned workspaces
// (adapter must match a harvested profile id+mode); subagent:<cell>@<adapter>#<mode>:<digest>
// for harness-native controls (EmitsSubagentEvents AND a non-empty delivery
// digest — event observation alone never promotes either control fact).
// Manifest booleans, unsmoked cells, unverified tiers, absent/skipped/
// malformed/non-qualifying rows stay unverified and never inherit
// HarnessRow.Caps. Dispatch (capability) and native (subagent) facts are
// separate and may differ.

// HarnessSupportContractVersion pins the per-harness support contract version.
const HarnessSupportContractVersion = "harness-support/v2"

// V2 axes in canonical order; sub-agent carries two distinct facts.
const (
	SupportAxisA2A                      = "a2a"
	SupportAxisArchitectureIntelligence = "architecture_intelligence"
	SupportAxisCodeIntelligence         = "code_intelligence"
	SupportAxisCredentialDelivery       = "credential_delivery" //nolint:gosec // G101: axis identifier, not a credential.
	SupportAxisHeadlessDispatch         = "headless_dispatch"
	SupportAxisInteractiveUse           = "interactive_use"
	SupportAxisLocalAuth                = "local_auth"
	SupportAxisSubagentControl          = "subagent_control"
	SupportAxisTokenCostAccuracy        = "token_cost_accuracy" //nolint:gosec // G101: axis identifier, not a credential.
)

var supportAxisOrder = []string{
	SupportAxisA2A,
	SupportAxisArchitectureIntelligence,
	SupportAxisCodeIntelligence,
	SupportAxisCredentialDelivery,
	SupportAxisHeadlessDispatch,
	SupportAxisInteractiveUse,
	SupportAxisLocalAuth,
	SupportAxisSubagentControl,
	SupportAxisTokenCostAccuracy,
}

// Capability IDs qualifying the fixture-derived axes; the adapter must match
// a harvested profile id+mode for the same harness.
const (
	supportCapA2A            = "a2a/v1"
	supportCapArchitecture   = "architecture_intelligence/v1"
	supportCapCode           = "code_intelligence/v1"
	supportCapTokenCost      = "token_cost_accuracy/v1" //nolint:gosec // G101: capability identifier, not a credential.
	supportCapDispatchSpaces = "dispatch_spawned_workspaces/v1"
)

// SupportLevel is the v2 value domain: supported, unsupported, or unverified.
type SupportLevel string

// Support levels for the v2 contract.
const (
	SupportSupported   SupportLevel = "supported"
	SupportUnsupported SupportLevel = "unsupported"
	SupportUnverified  SupportLevel = "unverified"
)

// SupportValue is one fact: level plus ordered public refs (none when unverified).
type SupportValue struct {
	Level    SupportLevel `json:"level"`
	Evidence []string     `json:"evidence"`
}

// SupportAxisEntry is one axis row; subagent_control carries the nested facts.
type SupportAxisEntry struct {
	Axis                      string        `json:"axis"`
	Level                     SupportLevel  `json:"level,omitempty"`
	Evidence                  []string      `json:"evidence,omitempty"`
	DispatchSpawnedWorkspaces *SupportValue `json:"dispatchSpawnedWorkspaces,omitempty"`
	HarnessNativeControls     *SupportValue `json:"harnessNativeControls,omitempty"`
}

// HarnessSupportV2 is the per-harness v2 contract embedded in HarnessRow.
type HarnessSupportV2 struct {
	ContractVersion string             `json:"contractVersion"`
	Axes            []SupportAxisEntry `json:"axes"`
}

// projectHarnessSupportV2 builds one harness contract from qualifying evidence
// in Built; it never reads Caps booleans as support.
func projectHarnessSupportV2(h HarnessRow, cells []HarnessEndpointCell, capabilities []CapabilityEligibilityRow, subagents []SubagentQualificationRow) HarnessSupportV2 {
	axes := make([]SupportAxisEntry, 0, len(supportAxisOrder))
	for _, axis := range supportAxisOrder {
		if axis == SupportAxisSubagentControl {
			dispatchLevel, dispatchEvidence := capabilityAxisSupport(h, capabilities, supportCapDispatchSpaces)
			nativeLevel, nativeEvidence := nativeControlsSupport(h, subagents)
			axes = append(axes, SupportAxisEntry{
				Axis:                      axis,
				DispatchSpawnedWorkspaces: &SupportValue{Level: dispatchLevel, Evidence: dispatchEvidence},
				HarnessNativeControls:     &SupportValue{Level: nativeLevel, Evidence: nativeEvidence},
			})
			continue
		}
		var level SupportLevel
		var evidence []string
		switch axis {
		case SupportAxisHeadlessDispatch:
			level, evidence = modeDispatchSupport(h, agent.PromptModeAutonomous, false)
		case SupportAxisInteractiveUse:
			level, evidence = modeDispatchSupport(h, agent.PromptModeHumanControlled, true)
		case SupportAxisLocalAuth:
			level, evidence = cellFlagSupport(h, cells, isLocalCell)
		case SupportAxisCredentialDelivery:
			level, evidence = cellFlagSupport(h, cells, needsKeyCell)
		case SupportAxisCodeIntelligence:
			level, evidence = capabilityAxisSupport(h, capabilities, supportCapCode)
		case SupportAxisA2A:
			level, evidence = capabilityAxisSupport(h, capabilities, supportCapA2A)
		case SupportAxisArchitectureIntelligence:
			level, evidence = capabilityAxisSupport(h, capabilities, supportCapArchitecture)
		case SupportAxisTokenCostAccuracy:
			level, evidence = capabilityAxisSupport(h, capabilities, supportCapTokenCost)
		default:
			level = SupportUnverified
		}
		axes = append(axes, SupportAxisEntry{Axis: axis, Level: level, Evidence: evidence})
	}
	return HarnessSupportV2{ContractVersion: HarnessSupportContractVersion, Axes: axes}
}

func hasToolProfile(h HarnessRow, adapter string, mode agent.PromptSessionMode) bool {
	for _, profile := range h.ToolLifecycle {
		if profile.ID == adapter && profile.Mode == mode {
			return true
		}
	}
	return false
}

func sortedUnique(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range in {
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	sort.Strings(out)
	return out
}

// isVerifiedDispatchProfile gates a headless/interactive positive on the
// profile's own evidence: a production-eligible profile or a verified tier.
// Unit-verified adapter declarations without production eligibility prove
// nothing and stay unverified.
func isVerifiedDispatchProfile(profile agent.ToolLifecycleProfile) bool {
	if profile.ProductionEligible {
		return true
	}
	switch profile.EvidenceTier {
	case "native_verified", "smoked":
		return true
	}
	return false
}

// modeDispatchSupport checks one session mode for a verified non-unsupported
// lifecycle delivery; all-unsupported is negative evidence, an unverified
// tier or a missing PTY grant stays unverified. The PTY flag is required
// only for the interactive mode.
func modeDispatchSupport(h HarnessRow, mode agent.PromptSessionMode, needPTY bool) (SupportLevel, []string) {
	var positive, negative []string
	hasMode := false
	hasUnprovenDelivery := false
	for _, profile := range h.ToolLifecycle {
		if profile.Mode != mode {
			continue
		}
		hasMode = true
		switch {
		case profile.LifecycleDelivery == agent.ToolDeliveryUnsupported:
			negative = append(negative, "profile:"+profile.ID)
		case isVerifiedDispatchProfile(profile):
			positive = append(positive, "profile:"+profile.ID)
		default:
			hasUnprovenDelivery = true
		}
	}
	if len(positive) > 0 {
		if !needPTY || h.Caps.SupportsInteractivePTY {
			return SupportSupported, sortedUnique(positive)
		}
		return SupportUnverified, nil
	}
	if hasUnprovenDelivery {
		return SupportUnverified, nil
	}
	if hasMode && len(negative) > 0 {
		return SupportUnsupported, sortedUnique(negative)
	}
	return SupportUnverified, nil
}

// cellFlagSupport needs a smoked, lane-proven cell passing match; an unsmoked
// or lane-less cell stays unverified. Supported refs cite the cell plus each
// proving smoke lane, so the doc evidence traces to the lane that proved it.
func cellFlagSupport(h HarnessRow, cells []HarnessEndpointCell, match func(HarnessEndpointCell) bool) (SupportLevel, []string) {
	var refs []string
	for _, c := range cells {
		if c.Harness != h.Name || !match(c) {
			continue
		}
		if !c.Smoked || len(c.ProvingLanes) == 0 {
			continue
		}
		refs = append(refs, "cell:"+string(c.Harness)+"/"+string(c.Endpoint)+"/"+string(c.Host))
		for _, lane := range c.ProvingLanes {
			refs = append(refs, "smoke:"+string(lane))
		}
	}
	if len(refs) > 0 {
		return SupportSupported, sortedUnique(refs)
	}
	return SupportUnverified, nil
}

func isLocalCell(c HarnessEndpointCell) bool {
	for _, am := range c.AuthModes {
		if am == agent.AuthLocal {
			return true
		}
	}
	return false
}

func needsKeyCell(c HarnessEndpointCell) bool { return c.NeedsAPIKey && !c.BringsOwnAuth }

// capabilityAxisSupport needs a smoked, production-eligible row for the exact
// capability whose adapter matches a harvested profile id+mode; plain-build
// emptiness stays unverified without inheriting Caps.
func capabilityAxisSupport(h HarnessRow, capabilities []CapabilityEligibilityRow, capabilityID string) (SupportLevel, []string) {
	var refs []string
	for _, row := range capabilities {
		if row.HarnessID != h.Name || row.CapabilityID != capabilityID {
			continue
		}
		if row.EvidenceTier != agent.CapabilityEvidenceSmoked || !row.ProductionEligible {
			continue
		}
		if !hasToolProfile(h, row.AdapterVersion, row.Mode) {
			continue
		}
		refs = append(refs, "capability:"+row.CapabilityID+"@"+row.AdapterVersion+"#"+string(row.Mode))
	}
	if len(refs) > 0 {
		return SupportSupported, sortedUnique(refs)
	}
	return SupportUnverified, nil
}

// nativeControlsSupport is the harness-native half: an executed fixture with
// EmitsSubagentEvents AND a non-empty delivery digest; events alone never
// promote it.
func nativeControlsSupport(h HarnessRow, subagents []SubagentQualificationRow) (SupportLevel, []string) {
	var refs []string
	for _, row := range subagents {
		if row.Cell.Harness != h.Name || !row.EmitsSubagentEvents || row.DeliveryInputDigest == "" || !hasToolProfile(h, row.AdapterVersion, row.Mode) {
			continue
		}
		refs = append(refs, "subagent:"+string(row.Cell.Harness)+"/"+string(row.Cell.Endpoint)+"/"+string(row.Cell.Host)+"@"+row.AdapterVersion+"#"+string(row.Mode)+":"+row.DeliveryInputDigest)
	}
	if len(refs) > 0 {
		return SupportSupported, sortedUnique(refs)
	}
	return SupportUnverified, nil
}

func v2Row(harness, axis, level, evidence string) string {
	return "| " + strings.Join([]string{escapeCell(harness), escapeCell(axis), escapeCell(level), escapeCell(evidence)}, " | ") + " |\n"
}

// renderSupportV2Section renders the v2 contract from the same in-memory rows
// the machine artifact carries; the sub-agent axis renders as two rows.
func renderSupportV2Section(built *Built) string {
	var buf strings.Builder
	buf.WriteString("\n## Harness support v2 (`" + HarnessSupportContractVersion + "`)\n\n")
	buf.WriteString("One evidence-backed fact per harness per v2 axis from the same contract\n")
	buf.WriteString("rows the machine artifact carries. Dispatch-spawned workspaces and\n")
	buf.WriteString("harness-native controls are separate facts.\n\n")
	buf.WriteString("| harness | axis | level | evidence |\n")
	buf.WriteString("| --- | --- | --- | --- |\n")
	harnesses := append([]HarnessRow(nil), built.Harnesses...)
	sort.Slice(harnesses, func(i, j int) bool { return harnesses[i].Name < harnesses[j].Name })
	for _, h := range harnesses {
		for _, axis := range h.SupportV2.Axes {
			if axis.Axis == SupportAxisSubagentControl {
				if axis.DispatchSpawnedWorkspaces != nil {
					buf.WriteString(v2Row(string(h.Name), axis.Axis+".dispatchSpawnedWorkspaces", string(axis.DispatchSpawnedWorkspaces.Level), strings.Join(axis.DispatchSpawnedWorkspaces.Evidence, ", ")))
				}
				if axis.HarnessNativeControls != nil {
					buf.WriteString(v2Row(string(h.Name), axis.Axis+".harnessNativeControls", string(axis.HarnessNativeControls.Level), strings.Join(axis.HarnessNativeControls.Evidence, ", ")))
				}
				continue
			}
			buf.WriteString(v2Row(string(h.Name), axis.Axis, string(axis.Level), strings.Join(axis.Evidence, ", ")))
		}
	}
	return buf.String()
}
